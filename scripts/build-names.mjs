// Builds data/names.txt, the first-name → gender lookup behind the poll
// estimates, from the World Gender Name Dictionary 2.0 (WIPO, CC0 1.0 public domain):
// https://doi.org/10.7910/DVN/MSEGSJ
//
//   node scripts/build-names.mjs [path/to/wgnd_2_0_sources.tab]
//
// Without a path it downloads wgnd_2_0_sources.tab (~175 MB) into dist/.
//
// Which names are kept: those found in sources with real counts (government
// name registers, where Indian names also appear through the diaspora), at
// least MIN_PEOPLE people. India's own source (IN_web) has no counts, so it
// isn't used to add names; it decides ties: a name India records for both
// genders (e.g. Kiran) is left out, so it counts as unknown.

import { createReadStream, createWriteStream, existsSync, mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { createInterface } from 'node:readline';
import { Readable } from 'node:stream';
import { pipeline } from 'node:stream/promises';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const SOURCE_URL = 'https://dataverse.harvard.edu/api/access/datafile/4750352';
const MIN_PEOPLE = 2;
const DECISIVE = 0.85; // share of one gender needed to call a name

async function sourceFile() {
  if (process.argv[2]) return process.argv[2];
  const file = join(ROOT, 'dist', 'wgnd_2_0_sources.tab');
  if (!existsSync(file)) {
    mkdirSync(dirname(file), { recursive: true });
    console.log('Downloading WGND 2.0 sources (~175 MB)…');
    const res = await fetch(SOURCE_URL);
    if (!res.ok) throw new Error(`Download failed: HTTP ${res.status}`);
    await pipeline(Readable.fromWeb(res.body), createWriteStream(file));
  }
  return file;
}

const unquote = (s) => s.replace(/^"|"$/g, '');

async function main() {
  const counted = new Map(); // name → [female people, male people]
  const india = new Map();   // name → { f, m } seen in IN_web
  const lines = createInterface({ input: createReadStream(await sourceFile()), crlfDelay: Infinity });
  let header = true;
  for await (const line of lines) {
    if (header) { header = false; continue; }
    const [rawName, , rawGender, , rawObs, rawSrc] = line.split('\t');
    if (!rawSrc) continue;
    const name = unquote(rawName);
    const gender = unquote(rawGender);
    if (!/^[a-z]{2,20}$/.test(name) || (gender !== 'F' && gender !== 'M')) continue;
    if (unquote(rawSrc) === 'IN_web') {
      const v = india.get(name) || { f: false, m: false };
      v[gender === 'F' ? 'f' : 'm'] = true;
      india.set(name, v);
    } else {
      const v = counted.get(name) || [0, 0];
      v[gender === 'F' ? 0 : 1] += Number(rawObs) || 0;
      counted.set(name, v);
    }
  }

  // U: known first names that are unisex. Listed so a lookup stops at them
  // ("Kiran Joseph" is unknown, not male because of "Joseph").
  const out = { F: [], M: [], U: [] };
  for (const [name, [f, m]] of counted) {
    if (f + m < MIN_PEOPLE) continue;
    const share = f / (f + m);
    const byCount = share >= DECISIVE ? 'F' : share <= 1 - DECISIVE ? 'M' : null;
    const inIndia = india.get(name);
    const byIndia = !inIndia ? null : inIndia.f && inIndia.m ? 'both' : inIndia.f ? 'F' : 'M';
    let gender = null;
    if (byIndia === 'both') gender = null; // unisex in India
    else if (byCount) gender = byIndia && byIndia !== byCount ? null : byCount;
    else gender = byIndia;
    out[gender || 'U'].push(name);
  }
  for (const list of Object.values(out)) list.sort();

  const file = join(ROOT, 'data', 'names.txt');
  mkdirSync(dirname(file), { recursive: true });
  writeFileSync(file, [
    '# First name → gender lookup for Unfollow Watch poll estimates.',
    '# Generated by scripts/build-names.mjs from the World Gender Name Dictionary 2.0',
    '# (WIPO, CC0 1.0 public domain): https://doi.org/10.7910/DVN/MSEGSJ',
    '# Lines after "F" are female names, after "M" male, after "U" unisex. Unlisted names are unknown.',
    'F', ...out.F,
    'M', ...out.M,
    'U', ...out.U,
    '',
  ].join('\n'));
  console.log(`data/names.txt: ${out.F.length} female, ${out.M.length} male, ${out.U.length} unisex names`);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
